// SetEmailReporter sets the email reporter for sending reports
func (rg *ReportGenerator) SetEmailReporter(emailRep *EmailReporter) {
	rg.emailRep = emailRep
}

// SendReport sends a generated report via email
func (rg *ReportGenerator) SendReport(to []string, subject string, reportPath string, scan *ScanResult) error {
	if rg.emailRep == nil {
		return fmt.Errorf("email reporter not configured")
	}
	if len(to) == 0 {
		return fmt.Errorf("recipients list cannot be empty")
	}
	return rg.emailRep.SendReport(to, subject, reportPath, scan)
}